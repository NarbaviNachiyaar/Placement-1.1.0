const now = new Date();
const iso = (d: Date) => d.toISOString();
const day = (offset: number) => {
  const d = new Date(now);
  d.setDate(d.getDate() + offset);
  return d.toISOString().slice(0, 10);
};
const at = (offset: number) => {
  const d = new Date(now);
  d.setDate(d.getDate() + offset);
  return iso(d);
};

